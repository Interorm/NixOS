"""
TRELLIS.2 image -> STL, shape stage only, for a Pascal GPU (GTX 1080 Ti, sm_61).

Differences from upstream app.py, all forced by the hardware:
  * no texture stage (needs Triton + nvdiffrast; an STL has no texture anyway)
  * attention via torch SDPA (ATTN_BACKEND=sdpa, see pascal.patch)
  * sparse conv via flex_gemm's torch "explicit_gemm" path (its Triton kernels need sm_70+)
  * fp32 compute: Pascal has no bf16.  The 1.3B flow models stay bf16 in host RAM and
    are converted to fp32 only while they are on the GPU (low_vram keeps one at a time).

Usage: trellis2-stl <config.json>   (generated by the NixOS module)
UI: one HTML page, FastAPI backend, three.js preview served from the Nix store ($TRELLIS2_STATIC).
"""
import json
