from pathlib import Path

import torch

CONFIG = json.loads(Path(sys.argv[1]).read_text())

import trellis2.modules.sparse.conv.config as conv_config  # noqa: E402
from trellis2.pipelines import Trellis2ImageTo3DPipeline  # noqa: E402

conv_config.FLEX_GEMM_ALGO = "explicit_gemm"

SHAPE_MODELS = [
    "sparse_structure_flow_model",
    "sparse_structure_decoder",
    "shape_slat_flow_model_512",
    "shape_slat_flow_model_1024",
    "shape_slat_decoder",
]


class ShapeOnlyPipeline(Trellis2ImageTo3DPipeline):
    model_names_to_load = SHAPE_MODELS


def local_pipeline_dir(models: dict) -> str:
    """Rewrite pipeline.json so every model resolves to the pre-downloaded local copies."""
    src = json.loads((Path(models["trellis2"]) / "pipeline.json").read_text())
    args = src["args"]
    for name, ref in args["models"].items():
        if ref.startswith("microsoft/TRELLIS-image-large/"):
            args["models"][name] = os.path.join(models["image_large"], ref.split("/", 2)[2])
        else:
            args["models"][name] = os.path.join(models["trellis2"], ref)
    args["image_cond_model"]["args"]["model_name"] = models["dinov3"]
    args["rembg_model"]["args"]["model_name"] = models["rmbg"]
    out = Path(tempfile.mkdtemp(prefix="trellis2-pipeline-"))
    (out / "pipeline.json").write_text(json.dumps(src))
    return str(out)


def fp32_while_on_gpu(model):
    """bf16 at rest on the CPU, fp32 on the GPU (instance-level .to/.cpu hooks)."""
    rest_dtype = model.dtype
    orig_to, orig_cpu = model.to, model.cpu

    def to(*args, **kwargs):
        orig_to(*args, **kwargs)
        model.convert_to(torch.float32)
        return model

    def cpu():
        model.convert_to(rest_dtype)
        return orig_cpu()

    model.to, model.cpu = to, cpu


def load_pipeline():
    t0 = time.time()
    p = ShapeOnlyPipeline.from_pretrained(local_pipeline_dir(CONFIG["models"]))
    p.low_vram = True
    for name, m in p.models.items():
        if hasattr(m, "convert_to"):            # DiT flow models (bf16 checkpoints)
            fp32_while_on_gpu(m)
        elif hasattr(m, "convert_to_fp32"):     # VAE decoders (fp16 checkpoints, small)
            m.convert_to_fp32()
            m.dtype = torch.float32
            if hasattr(m, "use_fp16"):
                m.use_fp16 = False
    p.cuda()
    print(f"[trellis2-stl] pipeline loaded in {time.time() - t0:.0f}s: {sorted(p.models)}", flush=True)
    return p


PIPELINE = load_pipeline()


GPU_LOCK = threading.Lock()   # one generation at a time; the GPU holds one model


@torch.no_grad()
def generate(image, resolution: str, seed: int, steps: int, target_faces: int, fill_holes: bool) -> dict:
    import trimesh

    p = PIPELINE
    t0 = time.time()
    torch.cuda.reset_peak_memory_stats()
    params = {"steps": int(steps)}
    image = p.preprocess_image(image)
    torch.manual_seed(int(seed))

    cond_512 = p.get_cond([image], 512)
    coords = p.sample_sparse_structure(cond_512, 32, 1, params)
    if resolution == "512":
        slat = p.sample_shape_slat(cond_512, p.models["shape_slat_flow_model_512"], coords, params)
        res = 512
    else:  # "1024_cascade"
        cond_1024 = p.get_cond([image], 1024)
        slat, res = p.sample_shape_slat_cascade(
            cond_512, cond_1024,
            p.models["shape_slat_flow_model_512"], p.models["shape_slat_flow_model_1024"],
            512, 1024, coords, params, CONFIG["max_num_tokens"],
        )
    torch.cuda.empty_cache()
    meshes, _ = p.decode_shape_slat(slat, res)
    mesh = meshes[0]
    if fill_holes:
        mesh.fill_holes()
    if target_faces and mesh.faces.shape[0] > target_faces:
        mesh.simplify(int(target_faces))

    # TRELLIS works Z-up (upstream's GLB export swaps to Y-up); slicers want Z-up,
    # so vertices go out unchanged.  Unit cube -> scale in the slicer.
    tm = trimesh.Trimesh(mesh.vertices.cpu().numpy(), mesh.faces.cpu().numpy(), process=True)
    out_dir = Path(CONFIG["output_dir"])
    out_dir.mkdir(parents=True, exist_ok=True)
    name = f"trellis2-{time.strftime('%Y%m%d-%H%M%S')}-s{int(seed)}-{res}.stl"
    tm.export(out_dir / name)
    torch.cuda.empty_cache()
    info = (f"{len(tm.faces):,} faces, watertight={tm.is_watertight}, "
            f"{time.time() - t0:.0f}s, peak VRAM {torch.cuda.max_memory_allocated() / 2**30:.1f} GiB")
    print(f"[trellis2-stl] {name}: {info}", flush=True)
    return {"file": name, "info": info}


