def app():
    import io
    from fastapi import FastAPI, File, Form, HTTPException, UploadFile
    from fastapi.responses import FileResponse, HTMLResponse
    from fastapi.staticfiles import StaticFiles
    from PIL import Image

    api = FastAPI(title="TRELLIS.2 -> STL")
    api.mount("/static", StaticFiles(directory=os.environ["TRELLIS2_STATIC"]), name="static")

    @api.get("/", response_class=HTMLResponse)
    def index():
        return PAGE

    @api.get("/health")
    def health():
        return {"ok": True, "busy": GPU_LOCK.locked()}

    @api.post("/generate")
    def run(image: UploadFile = File(...), resolution: str = Form("512"), seed: int = Form(42),
            steps: int = Form(12), max_faces: int = Form(300_000), fill_holes: bool = Form(False)):
        if resolution not in ("512", "1024_cascade"):
            raise HTTPException(400, "resolution must be 512 or 1024_cascade")
        if not GPU_LOCK.acquire(blocking=False):
            raise HTTPException(409, "busy with another generation")
        try:
            img = Image.open(io.BytesIO(image.file.read()))
            img.load()
            return generate(img, resolution, seed, max(1, min(steps, 50)), max_faces, fill_holes)
        except torch.cuda.OutOfMemoryError:
            # A stage that died mid-run is still on the GPU; park everything.
            for m in [*PIPELINE.models.values(), PIPELINE.image_cond_model, PIPELINE.rembg_model]:
                m.cpu()
            torch.cuda.empty_cache()
            raise HTTPException(507, "CUDA out of memory - try 512 or a lower maxNumTokens")
        finally:
            GPU_LOCK.release()

    @api.get("/outputs/{name}")
    def output(name: str):
        path = Path(CONFIG["output_dir"]) / Path(name).name      # no path traversal
        if not path.is_file():
            raise HTTPException(404)
        return FileResponse(path, media_type="model/stl", filename=path.name)

    return api


if __name__ == "__main__":
    import uvicorn
    uvicorn.run(app(), host=CONFIG["host"], port=CONFIG["port"])
